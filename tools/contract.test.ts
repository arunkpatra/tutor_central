import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { caseCopies, databaseFile, renderSample, renderSwift, stale } from "./contract";

test("the Swift file carries the header, the limits and the lists", () => {
  const swift = renderSwift({ limits: { tutorSaysMax: 300 }, lists: { eventKinds: ["a"] } });
  expect(swift).toContain("// Generated by bun contract from api/src/schemas.ts. Do not edit.");
  expect(swift).toContain("public static let tutorSaysMax = 300");
  expect(swift).toContain('public static let eventKinds = ["a"]');
  expect(swift).toContain("public enum APIContract {");
});

test("the database file is the generated types under a header", () => {
  const file = databaseFile("export type Json = string\n");
  expect(file.startsWith("// Generated by bun contract from supabase/types.ts. Do not edit.\n")).toBe(true);
  expect(file.endsWith("export type Json = string\n")).toBe(true);
});

test("a sample is JSON with sorted keys and two spaces", () => {
  expect(renderSample({ b: 1, a: { d: [1], c: "x" } })).toBe('{\n  "a": {\n    "c": "x",\n    "d": [\n      1\n    ]\n  },\n  "b": 1\n}\n');
});

test("stale names the files that differ, are missing, or are left over", async () => {
  const root = await mkdtemp(join(tmpdir(), "contract-"));
  try {
    await Bun.write(join(root, "a.txt"), "same");
    await Bun.write(join(root, "b.txt"), "old");
    await Bun.write(join(root, "dir/left.json"), "{}");
    const expected = new Map([
      ["a.txt", "same"],
      ["b.txt", "new"],
      ["c.txt", "missing"],
      ["dir/kept.json", "{}"],
    ]);
    expect((await stale(root, expected, ["dir"])).sort()).toEqual(["b.txt", "c.txt", "dir/kept.json", "dir/left.json"]);
  } finally {
    await rm(root, { recursive: true });
  }
});

test("each shared case file is copied into DomainTests' Cases (Phase 18: the budget, the reminders, the note week)", () => {
  expect(caseCopies()).toEqual([
    ["tools/contract/plan-cases.json", "ios/TutorCentralKit/Tests/DomainTests/Cases/plan-cases.json"],
    ["tools/contract/budget-cases.json", "ios/TutorCentralKit/Tests/DomainTests/Cases/budget-cases.json"],
    ["tools/contract/reminder-cases.json", "ios/TutorCentralKit/Tests/DomainTests/Cases/reminder-cases.json"],
    ["tools/contract/note-cases.json", "ios/TutorCentralKit/Tests/DomainTests/Cases/note-cases.json"],
  ]);
});
