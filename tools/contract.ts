#!/usr/bin/env bun
/** bun contract [--check]: the contract between the database, the API and the app (D80), generated so a limit lives once.
 *  Writes the API's database types from supabase/types.ts, the app's limits and lists from the API's schemas
 *  (api/src/contract.ts), the fake's sample answers, which the app's decoders read in ContractTests, and the shared
 *  case files' copies for DomainTests (the plan, the exam split in the budget's file, the note week; the reminders' cases
 *  stay the API's alone, since the server plans them), the syllabi's chapter names, and each agent's rubric as
 *  api/evals/<kind>/rubric.md. --check writes nothing: it names each generated file that is stale, missing or left over, and exits 1. */
import { readdir } from "node:fs/promises";
import { join, relative } from "node:path";

export type Contract = {
	limits: Record<string, number>;
	lists: Record<string, string[]>;
};

const ROOT = join(import.meta.dir, "..");
const DATABASE = "api/src/generated/database.ts";
const SWIFT = "ios/TutorCentralKit/Sources/Domain/Generated/APIContract.swift";
const SAMPLES = "ios/TutorCentralKit/Tests/DataTests/Contract";
/** The shared case files (written from Domain's rules, read by DomainTests and the API's ports), copied into the test
 *  target, which cannot reach a file outside its directory. */
const CASES = ["plan", "budget", "note"] as const;
const CASES_COPY = "ios/TutorCentralKit/Tests/DomainTests/Cases";
/** The syllabi's chapter names for the prompts' shared block (Phase 20 plan decision 5): the function bundles only api/. */
const SYLLABI = "api/src/generated/syllabi.ts";

type Syllabus = { board: string; classLevel: string; subject: string; chapters: { position: number; name: string }[] };

/** The chapter names by class, subject and board, in the books' order. */
export function renderSyllabi(syllabi: Syllabus[]): string {
	const table: Record<string, Record<string, Record<string, string[]>>> = {};
	const ordered = [...syllabi].sort((a, b) => a.classLevel.localeCompare(b.classLevel) || a.subject.localeCompare(b.subject) || a.board.localeCompare(b.board));
	for (const s of ordered) {
		const bySubject = (table[s.classLevel] ??= {});
		(bySubject[s.subject] ??= {})[s.board] = [...s.chapters].sort((a, b) => a.position - b.position).map((c) => c.name);
	}
	return [
		"// Generated by bun contract from supabase/syllabi. Do not edit.",
		"/** Chapter names by class, subject and board (the prompts' shared block, plan decision 5). */",
		`export const SYLLABI: Record<string, Record<string, Record<string, string[]>>> = ${JSON.stringify(table, null, 2)};`,
		"",
	].join("\n");
}

/** Each case file and where its copy goes. */
export function caseCopies(): [string, string][] {
	return CASES.map((name) => [
		`tools/contract/${name}-cases.json`,
		`${CASES_COPY}/${name}-cases.json`,
	]);
}

export function databaseFile(types: string): string {
	return `// Generated by bun contract from supabase/types.ts. Do not edit.\n${types}`;
}

export function renderSwift(c: Contract): string {
	const lines = [
		"// Generated by bun contract from api/src/schemas.ts. Do not edit.",
		"// swiftformat:disable all",
		"// swiftlint:disable all",
		"",
		"/// The API's limits and lists (api/src/contract.ts): a body the app sends keeps within them.",
		"public enum APIContract {",
		...Object.entries(c.limits).map(
			([name, value]) => `    public static let ${name} = ${value}`,
		),
		...Object.entries(c.lists).map(
			([name, values]) =>
				`    public static let ${name} = [${values.map((v) => JSON.stringify(v)).join(", ")}]`,
		),
		"}",
		"// swiftlint:enable all",
		"",
	];
	return lines.join("\n");
}

function sorted(value: unknown): unknown {
	if (Array.isArray(value)) return value.map(sorted);
	if (value && typeof value === "object") {
		return Object.fromEntries(
			Object.keys(value)
				.sort()
				.map((k) => [k, sorted((value as Record<string, unknown>)[k])]),
		);
	}
	return value;
}

export function renderSample(value: unknown): string {
	return `${JSON.stringify(sorted(value), null, 2)}\n`;
}

/** The API's contract and samples, read in the API's own package so its imports resolve as they do there. */
async function fromAPI(): Promise<{
	contract: Contract;
	samples: Record<string, unknown>;
	rubrics: Record<string, string>;
}> {
	const p = Bun.spawn(
		[
			"bun",
			"-e",
			'import { contract, samples } from "./src/contract.ts"; import { rubrics } from "./src/agents/kinds/index.ts"; console.log(JSON.stringify({ contract: contract(), samples: samples(), rubrics: rubrics() }))',
		],
		{ cwd: join(ROOT, "api"), stdout: "pipe", stderr: "pipe" },
	);
	const out = await new Response(p.stdout).text();
	if ((await p.exited) !== 0)
		throw new Error(
			`api/src/contract.ts did not run: ${await new Response(p.stderr).text()}`,
		);
	return JSON.parse(out);
}

/** Every generated file by its path from the repository's root. */
export async function expected(): Promise<Map<string, string>> {
	const { contract, samples, rubrics } = await fromAPI();
	const files = new Map<string, string>();
	files.set(
		DATABASE,
		databaseFile(await Bun.file(join(ROOT, "supabase/types.ts")).text()),
	);
	files.set(SWIFT, renderSwift(contract));
	for (const [kind, answer] of Object.entries(samples))
		files.set(`${SAMPLES}/${kind}.json`, renderSample(answer));
	for (const [from, to] of caseCopies())
		files.set(to, await Bun.file(join(ROOT, from)).text());
	const syllabi: Syllabus[] = [];
	for (const path of (await listed(ROOT, "supabase/syllabi")).filter((p) => p.endsWith(".json")))
		syllabi.push(await Bun.file(join(ROOT, path)).json());
	files.set(SYLLABI, renderSyllabi(syllabi));
	// Each kind's rubric (D101): the agent's check and promptfoo's graders read one text.
	for (const [kind, rubric] of Object.entries(rubrics))
		files.set(`api/evals/${kind}/rubric.md`, `${rubric}\n`);
	return files;
}

async function listed(root: string, dir: string): Promise<string[]> {
	try {
		const names = await readdir(join(root, dir), {
			recursive: true,
			withFileTypes: true,
		});
		return names
			.filter((n) => n.isFile())
			.map((n) => relative(root, join(n.parentPath, n.name)));
	} catch {
		return [];
	}
}

/** The paths that differ from what is expected, are missing, or sit in a generated directory unasked for. */
export async function stale(
	root: string,
	files: Map<string, string>,
	dirs: string[],
): Promise<string[]> {
	const out: string[] = [];
	for (const [path, content] of files) {
		const file = Bun.file(join(root, path));
		if (!(await file.exists()) || (await file.text()) !== content)
			out.push(path);
	}
	for (const dir of dirs)
		for (const path of await listed(root, dir))
			if (!files.has(path)) out.push(path);
	return out;
}

/** The generated files written, and what sits unasked for in a generated directory removed: `--check` and the write
 *  look at the same directories (the review's R-app-9: a retired case copy could not be cleared). */
export async function write(
	root: string,
	files: Map<string, string>,
	dirs: string[],
): Promise<void> {
	for (const dir of dirs)
		for (const path of await listed(root, dir))
			if (!files.has(path)) await Bun.file(join(root, path)).delete();
	for (const [path, content] of files)
		await Bun.write(join(root, path), content);
}

if (import.meta.main) {
	const files = await expected();
	const generated = [SAMPLES, CASES_COPY];
	if (process.argv.includes("--check")) {
		const paths = await stale(ROOT, files, generated);
		if (paths.length > 0) {
			console.error(
				`the contract is stale; run bun contract:\n${paths.map((p) => `  - ${p}`).join("\n")}`,
			);
			process.exit(1);
		}
		console.log("the contract is current");
	} else {
		await write(ROOT, files, generated);
		console.log(`wrote ${files.size} files`);
	}
}
